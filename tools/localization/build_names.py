#!/usr/bin/env python3
"""Emit the Android lookup tables from the reviewed evidence, without network access."""
import argparse
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tools/localization"
JAVA = ROOT / "app/src/main/java/dev/infend/skyrimtext"


def evidence():
    with (DATA / "evidence.tsv").open(encoding="utf-8") as stream:
        return list(csv.DictReader(stream, delimiter="\t"))


def record_id(row):
    form = row["original_id"]
    if form.startswith("XX"):
        return row["edition"].upper() + "_" + form[2:]
    return form


def shout_words():
    with (DATA / "shout_words.tsv").open(encoding="utf-8") as stream:
        return list(csv.DictReader(stream, delimiter="\t"))


def actor_references():
    with (DATA / "actor_references.tsv").open(encoding="utf-8") as stream:
        return list(csv.DictReader(stream, delimiter="\t"))


def java_source():
    all_rows = evidence()
    accepted = [r for r in all_rows if not r["review"]]
    word_evidence = {row["id"]: row["english"] for row in all_rows if row["kind"] == "word"}
    groups = {
        "SHOUTS": [(r["id"], r["canonical"], r["english"]) for r in accepted if r["kind"] == "shout-reference"],
        "WORDS": [(r["shout"], r["position"], r["word"], word_evidence[r["word"]], r["transcription"], r["meaning"])
                  for r in shout_words()],
        "NPC": [(r["id"], r["canonical"], record_id(r), r["english"]) for r in accepted
                if r["kind"] == "npc" and (r["original_id"] or r["prior"])],
        "ACTOR_REFERENCES": [(record_id(dict(edition=r["edition"], original_id=r["base_id"])),
                              record_id(dict(edition=r["edition"], original_id=r["reference_id"])))
                             for r in actor_references()],
        "RACES": [(r["canonical"], r["english"], r["original_id"]) for r in
                  sorted((r for r in accepted if r["kind"] == "race"), key=lambda r: int(r["id"]))],
        "CREATURES": [(r["id"], r["canonical"], r["english"]) for r in accepted
                      if r["kind"] == "creature" and r["prior"]],
        "ITEMS": [(r["id"], r["canonical"]) for r in accepted
                  if r["kind"] in {"item", "book", "armor", "weapon", "tome", "scroll"} and r["prior"]],
        "MAP_ALIASES": [(r["prior"], r["id"]) for r in accepted if r["kind"] == "map" and r["prior"]],
        "PERKS": [(r["id"], r["canonical"], r["prior"], r["original_id"]) for r in accepted if r["kind"] == "perk"],
        "QUESTS": [(r["id"], r["canonical"], r["prior"], r["original_id"], r["english"])
                   for r in accepted if r["kind"] in {"main-quest", "faction-quest"}],
    }
    lines = ["package dev.infend.skyrimtext;", "", "/** Generated by tools/localization/build_names.py. */",
             "final class RussianNameData {", "    private RussianNameData() {}"]
    for name, rows in groups.items():
        lines.append("    static final String[][] " + name + " = {")
        for row in rows:
            lines.append("        {" + ", ".join(json.dumps(v, ensure_ascii=False) for v in row) + "},")
        lines.append("    };")
    lines.extend([
        "    private static final java.util.Map<String, String> NPC_NAMES = new java.util.HashMap<>();",
        "    static { for (String[] row : NPC) NPC_NAMES.put(row[0], row[1]); }",
        "    static String npcName(String key) { return NPC_NAMES.getOrDefault(key, key); }",
    ])
    lines += ["}", "", "final class RussianItemIdentityData {", "    private RussianItemIdentityData() {}"]
    item_kinds = {"item", "weapon", "armor", "book", "tome", "scroll"}
    records = [(r["id"], record_id(r), r["english"]) for r in accepted
               if r["kind"] in item_kinds and re.fullmatch(r"(?:00|XX)[0-9A-F]{6}", r["original_id"])]
    # Keep each generated initializer below the JVM bytecode method-size limit.
    chunks = [records[start:start + 160] for start in range(0, len(records), 160)]
    methods = ", ".join(f"part{i}()" for i in range(len(chunks)))
    lines.append("    static final String[][][] PARTS = {" + methods + "};")
    for i, rows in enumerate(chunks):
        lines += [f"    private static String[][] part{i}() {{", "        return new String[][] {"]
        for row in rows:
            lines.append("            {" + ", ".join(json.dumps(x, ensure_ascii=False) for x in row) + "},")
        lines += ["        };", "    }"]
    return "\n".join([*lines, "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = JAVA / "RussianNameData.java"
    source = java_source()
    if args.check:
        if target.read_text(encoding="utf-8") != source:
            raise SystemExit("RussianNameData.java differs from evidence.tsv")
    else:
        target.write_text(source, encoding="utf-8")
