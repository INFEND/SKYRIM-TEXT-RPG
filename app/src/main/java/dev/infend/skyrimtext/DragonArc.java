    public static String status(GameEngine g){
        int stage=Math.max(0,Math.min(FINAL_STAGE,g.progress.dragonStage));
        return stage==FINAL_STAGE?"Завершено: первое испытание":CHAPTERS[stage]+" • "+PROGRESS[stage];
    }
    public static GameEngine.Scene scene(GameEngine g){
        int stage=Math.max(0,Math.min(FINAL_STAGE,g.progress.dragonStage));
        if(stage==FINAL_STAGE)
            return new GameEngine.Scene("ПЕРВАЯ САГА ЗАВЕРШЕНА","Голос среди гор",
                "Уцелевшие жители долин рассказывают о сражении у сторожевой башни. На вершине ты услышал, что сила без понимания превращается в новую беду. Знание о драконах теперь часть твоего пути.\n\nЭто завершение первой самостоятельной сюжетной арки. Впереди остаётся исследование Скайрима, другие задания и ещё не раскрытые древние тайны.")
                .primary("GO_WORLD","Вернуться в большой мир","Продолжить приключение и другие задания");
        String destination=DESTINATIONS[stage];
        boolean arrived=destination.equals(g.progress.location);
        String suffix=g.progress.dragonRecent.isEmpty()?"":"\n\nПОСЛЕДСТВИЕ ПОСЛЕДНЕГО ВЫБОРА\n"+g.progress.dragonRecent;
        GameEngine.Scene s=new GameEngine.Scene("ДРАКОНИЙ СЛЕД • ГЛАВА "+(stage+1),
            CHAPTERS[stage],NARRATIVE[stage]+"\n\nЦЕЛЬ: "+PROGRESS[stage]+
            "\nМЕСТО: "+destination+(arrived?" • ты здесь":" • требуется путь")+suffix);
        s.primary("DRAGON:"+stage+":0",arrived?ADVANCE[stage]:"Проложить путь в "+destination,
            arrived?"Продолжить главную историю":"Открыть дороги и выбрать путь к цели");
        for(int i=1;i<=8;i++){
            String[] split=OPTIONS[stage][i-1].split("\\|",2);
            boolean attempted=g.progress.dragonUsed.contains("DRAGON:"+stage+":"+i);
            s.add("DRAGON:"+stage+":"+i,(attempted?"✓ ":"")+split[0],
                attempted?"Уже выполнено в этой главе":!arrived?"Сначала доберись до места главы":split[1]);
        }
        s.add("DRAGON:"+stage+":9","Вернуться к исследованию мира","Сохранить текущую главу и продолжить путь позднее");
        return s;
    }

    /** Percent returned here is used by the exact same roll in perform(). */
    public static int chance(GameEngine g,String action){
        if(!"DRAGON".equals(g.mode)||action==null||!action.matches("DRAGON:[0-5]:[0-9]"))return -1;
        String[] tokens=action.split(":");
        int stage=Integer.parseInt(tokens[1]),index=Integer.parseInt(tokens[2]);
        if(stage!=g.progress.dragonStage||g.progress.dragonUsed.contains(action))return -1;
        if(!DESTINATIONS[stage].equals(g.progress.location))return -1;
        if(index!=3&&index!=5&&index!=7)return -1;
        if(g.stamina<7)return -1;
        int skill=SKILLS[index-1];
        return g.progress.chance(g,index%3,skill,DIFFICULTY[index-1]+stage*3);
    }

    /**
     * @return true if stage 4 should enter the dragon encounter.
     */
    public static boolean perform(GameEngine g,String action){
        if(!"DRAGON".equals(g.mode)||action==null||!action.matches("DRAGON:[0-5]:[0-9]"))return false;
        String[] tokens=action.split(":");
        int stage=Integer.parseInt(tokens[1]),index=Integer.parseInt(tokens[2]);
        if(stage!=g.progress.dragonStage)return false;
        if(index==9){g.mode="WORLD";return false;}
        if(index==0){
            if(!DESTINATIONS[stage].equals(g.progress.location)){
                g.mode="TRAVEL";
                g.message="Для продолжения истории отправься в "+DESTINATIONS[stage]+".";
                return false;
            }
            if(stage==3)return true;
            g.progress.dragonStage++;
            int xpReward=18+stage*9;
            g.addXp(xpReward);
            g.progress.dragonRecent="Глава «"+CHAPTERS[stage]+"» пройдена. Получено "+xpReward+
                " опыта. Твоя история продолжается.";
            if(stage==5)g.progress.completed.add("Драконий след • первое испытание • день "+g.day);
            g.mode="DRAGON";
            return false;
        }
        if(g.progress.dragonUsed.contains(action)){
            g.progress.dragonRecent="Этот путь уже пройден. Повторное действие не даёт новых наград.";
            return false;
        }
        if(!DESTINATIONS[stage].equals(g.progress.location)){
            g.progress.dragonRecent="Сначала доберись до места главы: "+DESTINATIONS[stage]+". Удалённые действия недоступны.";
            return false;
        }
        if((index==3||index==5||index==7)&&g.stamina<7){
            g.progress.dragonRecent="Ты слишком истощён для опасной попытки. Отдохни перед испытанием.";
            return false;
        }
        int check=chance(g,action);
        g.progress.dragonUsed.add(action);
        String[] option=OPTIONS[stage][index-1].split("\\|",2);
        g.day+=1; // A choice costs a portion of the day and cannot be farmed.
        if(check>=0){
            boolean success=new Random().nextInt(100)<check;
            g.stamina=Math.max(0,g.stamina-7);
            if(success){
                g.progress.dragonInsight=Math.min(15,g.progress.dragonInsight+2);
                g.progress.skillExperience(g,SKILLS[index-1],12+stage*3);
                g.progress.dragonRecent="Удалось: "+option[0]+". "+option[1]+
                    " Появилось новое свидетельство, которое поможет в сражении. Получен опыт навыка.";
            }else{
                int wound=3+stage*2;
                g.hp=Math.max(1,g.hp-wound);
                g.progress.dragonRecent="Попытка не удалась: "+option[0]+". "+
                    "Неосторожность обошлась в "+wound+" здоровья. Дальнейший путь остаётся открытым.";
            }
        }else{
            switch(index){
                case 1:g.progress.dragonInsight=Math.min(15,g.progress.dragonInsight+1);break;
                case 2:g.reputation=Math.min(50,g.reputation+1);break;
                case 4:g.progress.skillExperience(g,15,5);break;
                case 6:g.stamina=Math.min(g.maxStamina,g.stamina+12);break;
                case 8:g.progress.dragonInsight=Math.min(15,g.progress.dragonInsight+1);break;
                default:break;
            }
            g.progress.dragonRecent="Ты выбираешь: "+option[0]+". "+option[1]+
                " Этот шаг оставил след в твоей истории. Вернуться к нему за новой наградой нельзя.";
        }
        return false;
    }
