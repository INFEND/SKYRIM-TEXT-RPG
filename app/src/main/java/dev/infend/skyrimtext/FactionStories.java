    private final int[] index=new int[DATA.length],phase=new int[DATA.length],attemptDay=new int[DATA.length];
    FactionStories(){java.util.Arrays.fill(attemptDay,-1);}
    int count(int f){return DATA[f].length;}
    int done(int f){return index[f];}
    boolean started(int f){return index[f]>0||phase[f]>0;}
    boolean completed(int f){return index[f]>=count(f);}
    Chapter chapter(int f){return completed(f)?null:new Chapter(DATA[f][index[f]]);}
    int phase(int f){return phase[f];}
    String block(GameEngine g,int f){
        if(!g.started||"COMBAT".equals(g.mode)||"DEFEAT".equals(g.mode))return "Сначала заверши текущую сцену.";
        if(completed(f))return "Кампания завершена.";
        if(f==4&&(started(5)||g.factions.stage(5)>0)||f==5&&(started(4)||g.factions.stage(4)>0))return "Ты выбрал другую сторону гражданской войны.";
        if(!chapter(f).place.equalsIgnoreCase(g.progress.location))return "Прибудь: "+chapter(f).place;
        if(phase[f]==1&&attemptDay[f]==g.day)return "Следующая попытка в другой игровой день.";
        if(phase[f]==1&&g.stamina<8)return "Нужно 8 выносливости.";
        return "";
    }
    int chance(GameEngine g,int f){Chapter c=chapter(f);return c==null||phase[f]!=1||!c.enemy.isEmpty()?-1:g.progress.chance(g,2,c.skill,20+Math.min(30,index[f]*3));}
    boolean advance(GameEngine g,int f){
        if(!block(g,f).isEmpty())return false;Chapter c=chapter(f);
        if(phase[f]==0){phase[f]=1;g.progress.setQuestOutcome("faction_story_"+f,"ACTIVE");g.message=c.story;return true;}
        if(phase[f]==2){index[f]++;phase[f]=0;attemptDay[f]=-1;g.progress.skillExperience(g,c.skill,35);g.addXp(30+index[f]*5);g.gold=(int)Math.min(Integer.MAX_VALUE,(long)g.gold+25+index[f]*5);g.progress.sync(g);g.message="Завершено: "+c.title;if(completed(f))g.progress.setQuestOutcome("faction_story_"+f,"COMPLETED");g.recordVisualEvent(g.message);return true;}
        int chance=chance(g,f);g.stamina-=8;attemptDay[f]=g.day;
        if(!c.enemy.isEmpty()){g.beginFactionBattle(f,c.enemy,45+g.level*10+index[f]*7,6+g.level*2,c.story);return true;}
        if(new java.util.Random().nextInt(100)<chance){phase[f]=2;g.message="Испытание пройдено. Заверши главу.";}else g.message="Попытка не удалась. Отдохни и попробуй в другой день.";
        return true;
    }
    void victory(int f){if(f>=0&&f<DATA.length&&!completed(f)&&phase[f]==1&&!chapter(f).enemy.isEmpty())phase[f]=2;}
    JSONObject toJson(){JSONObject o=new JSONObject();try{o.put("index",new JSONArray(index)).put("phase",new JSONArray(phase)).put("attemptDay",new JSONArray(attemptDay));}catch(Exception ignored){}return o;}
    static FactionStories fromJson(JSONObject o){FactionStories s=new FactionStories();if(o==null)return s;JSONArray a=o.optJSONArray("index"),b=o.optJSONArray("phase"),d=o.optJSONArray("attemptDay");for(int f=0;f<DATA.length;f++){s.index[f]=a==null?0:Math.max(0,Math.min(s.count(f),a.optInt(f)));s.phase[f]=b==null?0:Math.max(0,Math.min(2,b.optInt(f)));s.attemptDay[f]=d==null?-1:d.optInt(f,-1);}return s;}
