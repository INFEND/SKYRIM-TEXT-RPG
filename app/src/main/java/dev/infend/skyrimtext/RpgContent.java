    public static int successChance(GameEngine g,int stat,int difficulty,int danger,int fatigue,int situational){
        // Transparent deterministic percentile estimator, independent of the random roll.
        // Level gap and exhaustion meaningfully reduce chances. No success guarantee on hard checks.
        int attribute=(stat==0?g.maxHp:stat==1?g.maxMagicka:g.maxStamina);
        int score=50+(attribute-100)/7+g.level*2+difficulty*-1-danger*3-fatigue/5+situational;
        int charisma=g.reputation/5;score+=Math.max(-10,Math.min(10,charisma));
        return Math.max(0,Math.min(100,score));
    }
